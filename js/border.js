// ===========================================================================
//   دالة التحقق من التواجد داخل الحدود (Point-in-Polygon)
// ===========================================================================
function isInsideSaudi(lat, lng) {
    let inside = false;
    for (let i = 0, j = saudiBorder.length - 1; i < saudiBorder.length; j = i++) {
        let xi = saudiBorder[i][0], yi = saudiBorder[i][1];
        let xj = saudiBorder[j][0], yj = saudiBorder[j][1];

        let intersect = ((yi > lng) !== (yj > lng)) &&
            (lat < (xj - xi) * (lng - yi) / (yj - yi) + xi);
        if (intersect) inside = !inside;
    }
    return inside;
}