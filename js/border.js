// ===========================================================================
//  دالة التحقق السيادي — تمنع أي تداخل للأراضي الأجنبية وتراقب الاختراق
// ===========================================================================
function isInsideSaudi(lat, lng) {
    // رفض سريع إذا كانت الإحداثيات خارج النطاق الجغرافي العام للمملكة
    if (lat > 32.3 || lat < 16.5 || lng < 34.6 || lng > 55.3) return false;

    // استثناءات المناطق المجاورة لضمان الدقة (قطر، البحرين، الإمارات، اليمن)
    if (lat >= 24.5 && lat <= 26.2 && lng >= 50.75 && lng <= 51.65) return false; // قطر
    if (lat >= 25.8 && lat <= 26.4 && lng >= 50.3 && lng <= 50.7) return false;   // البحرين
    if (lng >= 55.12 && lat >= 22.5 && lat <= 26.2) return false;               // الإمارات
    if (lat < 16.55) return false;                                               // اليمن جنوب جازان

    // خوارزمية النقطة داخل المضلع (Ray Casting Algorithm)
    let inside = false;
    for (let i = 0, j = saudiBorder.length - 1; i < saudiBorder.length; j = i++) {
        const xi = saudiBorder[i][0], yi = saudiBorder[i][1];
        const xj = saudiBorder[j][0], yj = saudiBorder[j][1];
        const intersect = ((yi > lng) !== (yj > lng)) &&
            (lat < (xj - xi) * (lng - yi) / (yj - yi) + xi);
        if (intersect) inside = !inside;
    }
    return inside;
}